//! Property test for the Activity_Log line format.
//!
//! **Property 28: Log line format** — *for any* `LogEntry` with arbitrary
//! string fields, `format_entry` produces exactly one line of valid UTF-8 with
//! no CR or LF. It starts with a timestamp matching
//! `YYYY-MM-DD HH:MM:SS.mmm ±HH:MM`, and for save/restore entries the counts
//! equal those of the snapshot or plan it describes.
//!
//! **Validates: Requirements 13.1, 13.2, 13.5**

mod common;

use common::strategies::*;
use esr_core::logfmt::entry::{format_entry, parse_line, LogEntry};
use esr_core::model::*;
use esr_core::plan::fallback::OmitReason;
use proptest::collection::vec;
use proptest::prelude::*;
use proptest::sample::select;

// ---------------------------------------------------------------------------
// Test-side expectations (independent of the implementation's token tables)
// ---------------------------------------------------------------------------

/// The Req 13.1 save causes, one token each.
const SAVE_CAUSE_TOKENS: [(SaveCause, &str); 8] = [
    (SaveCause::LastWindowClosed, "last-window-closed"),
    (SaveCause::LastTabClosed, "last-tab-closed"),
    (SaveCause::ExplorerTerminated, "explorer-terminated"),
    (SaveCause::SignOut, "sign-out"),
    (SaveCause::Shutdown, "shutdown"),
    (SaveCause::Restart, "restart"),
    (SaveCause::ExitThroughSettings, "exit-through-settings"),
    // A checkpoint is only logged when found at the next start (Req 13.1,
    // "abrupt Session_Monitor end or power loss detected at the next start").
    (SaveCause::Checkpoint, "abrupt-end-detected-at-start"),
];

/// The Req 9.7 omission reasons, one token each.
const OMIT_REASON_TOKENS: [(OmitReason, &str); 5] = [
    (OmitReason::NotExist, "does-not-exist"),
    (OmitReason::Inaccessible, "inaccessible"),
    (OmitReason::Timeout, "no-response-within-5s"),
    (OmitReason::Unresolvable, "identifier-unresolvable"),
    (OmitReason::ShellUnavailable, "shell-location-unavailable"),
];

fn cause_token(cause: SaveCause) -> &'static str {
    SAVE_CAUSE_TOKENS.iter().find(|(c, _)| *c == cause).unwrap().1
}

fn reason_token(reason: OmitReason) -> &'static str {
    OMIT_REASON_TOKENS.iter().find(|(r, _)| *r == reason).unwrap().1
}

fn w(s: &str) -> WideString {
    WideString::from(s)
}

/// The `key=value` fields `entry` must produce, in line order, with the
/// original (unescaped) values.
fn expected_fields(entry: &LogEntry) -> Vec<(&'static str, WideString)> {
    let n = |v: &dyn ToString| w(&v.to_string());
    match entry {
        LogEntry::Save { cause, windows, tabs } => vec![
            ("cause", w(cause_token(*cause))),
            ("windows", n(windows)),
            ("tabs", n(tabs)),
        ],
        LogEntry::Restore { targeted, windows, tabs, omitted, redirected, duration_ms } => vec![
            ("launch", w(if *targeted { "targeted" } else { "default" })),
            ("windows", n(windows)),
            ("tabs", n(tabs)),
            ("omitted", n(omitted)),
            ("redirected", n(redirected)),
            ("duration_ms", n(duration_ms)),
        ],
        LogEntry::TabOmitted { location, reason } => vec![
            ("location", location.parsing_name.clone()),
            ("reason", w(reason_token(*reason))),
        ],
        LogEntry::TabRedirected { location, reason, ancestor } => vec![
            ("location", location.parsing_name.clone()),
            ("reason", w(reason_token(*reason))),
            ("ancestor", ancestor.parsing_name.clone()),
        ],
        LogEntry::Error { operation, description } => {
            vec![("operation", w(operation)), ("description", w(description))]
        }
        LogEntry::CapExcluded { windows, tabs } => vec![("windows", n(windows)), ("tabs", n(tabs))],
        LogEntry::UnidentifiableLocation { kept_previous } => {
            vec![("action", w(if *kept_previous { "kept-previous" } else { "tab-excluded" }))]
        }
        LogEntry::Abandoned => vec![("failed_attempts", n(&MAX_FAILED_ATTEMPTS))],
        LogEntry::BuiltinRestoreDetected => vec![],
        LogEntry::TabsDeferred { distinct, immediate, deferred, budget } => vec![
            ("distinct", n(distinct)),
            ("immediate", n(immediate)),
            ("deferred", n(deferred)),
            ("budget", n(budget)),
        ],
        // Not generated here: FOLD entries are covered by prop_fold_log.rs (Property 40).
        LogEntry::Fold { .. } => unreachable!("FOLD entries are not generated by log_entry()"),
    }
}

/// Independent rendering of `YYYY-MM-DD HH:MM:SS.mmm ±HH:MM`.
fn expected_timestamp(ts: &Timestamp) -> String {
    let sign = if ts.offset_minutes < 0 { '-' } else { '+' };
    let off = ts.offset_minutes.unsigned_abs();
    format!(
        "{:04}-{:02}-{:02} {:02}:{:02}:{:02}.{:03} {sign}{:02}:{:02}",
        ts.year, ts.month, ts.day, ts.hour, ts.minute, ts.second, ts.millis, off / 60, off % 60
    )
}

/// True if `prefix` has the shape `DDDD-DD-DD DD:DD:DD.DDD ±DD:DD ` (D a digit).
fn has_timestamp_shape(prefix: &[u8]) -> bool {
    const SHAPE: &[u8] = b"dddd-dd-dd dd:dd:dd.ddd sdd:dd ";
    prefix.len() == SHAPE.len()
        && SHAPE.iter().zip(prefix).all(|(&s, &b)| match s {
            b'd' => b.is_ascii_digit(),
            b's' => b == b'+' || b == b'-',
            _ => s == b,
        })
}

// ---------------------------------------------------------------------------
// Strategies
// ---------------------------------------------------------------------------

/// Characters that stress the line format: separators, line breaks of every
/// kind, the escape character, BOM, NUL, C1 controls, astral characters.
const NASTY_CHARS: &[char] = &[
    ' ', '=', '%', '\r', '\n', '\t', '\0', '\u{7F}', '\u{85}', '\u{9F}', '\u{A0}', '\u{2028}',
    '\u{2029}', '\u{FEFF}', '\u{FFFD}', '\u{1F600}', 'é', 'e', '\u{301}',
];

/// Arbitrary Rust strings, weighted towards [`NASTY_CHARS`].
fn log_string() -> impl Strategy<Value = String> {
    prop_oneof![
        1 => any::<String>(),
        3 => vec(prop_oneof![2 => any::<char>(), 1 => select(NASTY_CHARS)], 0..48)
            .prop_map(|cs| cs.into_iter().collect::<String>()),
    ]
}

fn omit_reason() -> impl Strategy<Value = OmitReason> {
    select(OMIT_REASON_TOKENS.iter().map(|(r, _)| *r).collect::<Vec<_>>())
}

/// Every `LogEntry` variant with arbitrary fields.
fn log_entry() -> impl Strategy<Value = LogEntry> {
    prop_oneof![
        (save_cause(), any::<u32>(), any::<u32>())
            .prop_map(|(cause, windows, tabs)| LogEntry::Save { cause, windows, tabs }),
        (any::<bool>(), any::<u32>(), any::<u32>(), any::<u32>(), any::<u32>(), any::<u64>()).prop_map(
            |(targeted, windows, tabs, omitted, redirected, duration_ms)| LogEntry::Restore {
                targeted,
                windows,
                tabs,
                omitted,
                redirected,
                duration_ms,
            }
        ),
        (location_id(), omit_reason())
            .prop_map(|(location, reason)| LogEntry::TabOmitted { location, reason }),
        (location_id(), omit_reason(), location_id()).prop_map(|(location, reason, ancestor)| {
            LogEntry::TabRedirected { location, reason, ancestor }
        }),
        (log_string(), log_string())
            .prop_map(|(operation, description)| LogEntry::Error { operation, description }),
        (any::<u32>(), any::<u32>()).prop_map(|(windows, tabs)| LogEntry::CapExcluded { windows, tabs }),
        any::<bool>().prop_map(|kept_previous| LogEntry::UnidentifiableLocation { kept_previous }),
        Just(LogEntry::Abandoned),
        Just(LogEntry::BuiltinRestoreDetected),
        (any::<u32>(), any::<u32>(), any::<u32>(), any::<u32>()).prop_map(|(distinct, immediate, deferred, budget)| {
            LogEntry::TabsDeferred { distinct, immediate, deferred, budget }
        }),
    ]
}

// ---------------------------------------------------------------------------
// Property
// ---------------------------------------------------------------------------

proptest! {
    #![proptest_config(ProptestConfig::with_cases(512))]

    /// **Property 28: Log line format**
    ///
    /// **Validates: Requirements 13.1, 13.2, 13.5**
    #[test]
    fn log_line_format(ts in timestamp(), entry in log_entry()) {
        let line: String = format_entry(&ts, &entry);

        // Req 13.5: a single line (no CR/LF), no BOM. Being a `String`, the
        // line is valid UTF-8 by construction; check the bytes anyway.
        prop_assert!(!line.contains(['\r', '\n']), "line break in {:?}", line);
        prop_assert!(!line.starts_with('\u{FEFF}'), "BOM in {:?}", line);
        prop_assert!(std::str::from_utf8(line.as_bytes()).is_ok());

        // Req 13.5: starts with `YYYY-MM-DD HH:MM:SS.mmm ±HH:MM `.
        let prefix = format!("{} ", expected_timestamp(&ts));
        prop_assert!(has_timestamp_shape(prefix.as_bytes()), "bad expected prefix {:?}", prefix);
        prop_assert!(line.starts_with(&prefix), "{:?} does not start with {:?}", line, prefix);

        // The line splits back into timestamp, event and fields.
        let parsed = parse_line(&line);
        prop_assert!(parsed.is_some(), "unparsable line {:?}", line);
        let parsed = parsed.unwrap();
        prop_assert_eq!(&parsed.timestamp, &ts);
        prop_assert_eq!(parsed.event.as_str(), entry.event_name());
        prop_assert_eq!(
            &line[prefix.len()..prefix.len() + entry.event_name().len()],
            entry.event_name()
        );

        // Keys in order, every value unescaping back to the original
        // (parsing names with lone surrogates, Error strings, counts).
        let expected = expected_fields(&entry);
        let actual: Vec<(&str, &WideString)> =
            parsed.fields.iter().map(|(k, v)| (k.as_str(), v)).collect();
        let expected_ref: Vec<(&str, &WideString)> =
            expected.iter().map(|(k, v)| (*k, v)).collect();
        prop_assert_eq!(actual, expected_ref, "line {:?}", line);

        match &entry {
            // Req 13.1: the cause is exactly one of the listed causes.
            LogEntry::Save { .. } => {
                let cause = parsed.get_str("cause").unwrap();
                let matches = SAVE_CAUSE_TOKENS.iter().filter(|(_, t)| *t == cause).count();
                prop_assert_eq!(matches, 1, "cause {:?}", cause);
            }
            // Req 13.2: launch type and all counts plus the duration.
            LogEntry::Restore { .. } => {
                let launch = parsed.get_str("launch").unwrap();
                prop_assert!(launch == "default" || launch == "targeted", "launch {:?}", launch);
                for key in ["windows", "tabs", "omitted", "redirected", "duration_ms"] {
                    prop_assert!(parsed.get(key).is_some(), "missing {} in {:?}", key, line);
                }
            }
            _ => {}
        }
    }
}

/// The token tables cover every cause/reason with distinct tokens, so
/// "exactly one of" in the property is meaningful.
#[test]
fn token_tables_are_complete_and_distinct() {
    assert_eq!(ALL_SAVE_CAUSES.len(), SAVE_CAUSE_TOKENS.len());
    for cause in ALL_SAVE_CAUSES {
        let _ = cause_token(cause);
    }
    let mut tokens: Vec<_> = SAVE_CAUSE_TOKENS.iter().map(|(_, t)| *t).collect();
    tokens.sort_unstable();
    tokens.dedup();
    assert_eq!(tokens.len(), SAVE_CAUSE_TOKENS.len());
}
